<?php
$pageTitle = 'Remote Data + Caching (Filesystem)';

require_once __DIR__ . '/../lib/functions.php';

// Remote CSV source (public dataset). If it is slow or unavailable, the page
// will show an error message, and you can still discuss the caching logic.
$dataUrl = 'https://www.maine.gov/labor/cwri/laus/Population1960_2000.csv';

$cacheDir = __DIR__ . '/../storage/cache';
if (!is_dir($cacheDir)) {
    mkdir($cacheDir, 0777, true);
}

$cacheFile = $cacheDir . '/cached-population-table.html';

$ttlDays = 7;
$ttlSeconds = $ttlDays * 86400;

$refresh = $_GET['refresh'] ?? '';
$refresh = is_string($refresh) ? $refresh : '';
$refresh = $refresh === '1';

$maxRowsRaw = $_GET['max'] ?? '16';
$maxRowsRaw = is_string($maxRowsRaw) ? $maxRowsRaw : '16';
$maxRows = (int) $maxRowsRaw;
if ($maxRows < 1 || $maxRows > 100) {
    $maxRows = 16;
}

$cacheAgeSeconds = is_file($cacheFile) ? (time() - (int) filemtime($cacheFile)) : null;
$cacheFresh = $cacheAgeSeconds !== null && $cacheAgeSeconds <= $ttlSeconds;

$source = '';
$tableHtml = '';
$error = '';

if (!$refresh && $cacheFresh) {
    $cached = file_get_contents($cacheFile);
    if (is_string($cached)) {
        $source = 'cache';
        $tableHtml = $cached;
    } else {
        $error = 'Could not read cache file.';
    }
}

if ($tableHtml === '') {
    $source = 'remote';

    $context = stream_context_create([
        'http' => [
            'timeout' => 8,
            'header' => "User-Agent: CIS333-Class9\r\n",
        ],
    ]);

    $handle = fopen($dataUrl, 'r', false, $context);
    if ($handle === false) {
        $error = 'Could not open remote URL. (Check allow_url_fopen and network access.)';
    } else {
        // Build HTML in a string so we can both display it and cache it.
        ob_start();
        print '<table border="1" cellpadding="6">';
        print '<thead><tr><th>County</th><th>Population (2000)</th></tr></thead>';
        print '<tbody>';

        $rowsPrinted = 0;

        while (($line = fgetcsv($handle)) !== false) {
            // The dataset includes both towns and counties.
            // Column 1 is a label like "County" for county rows.
            if (($line[1] ?? '') !== 'County') {
                continue;
            }

            $countyName = (string) ($line[0] ?? '');
            $population2000 = (string) ($line[6] ?? '');

            print '<tr>';
            print '<td>' . h($countyName) . '</td>';
            print '<td>' . h($population2000) . '</td>';
            print '</tr>';

            $rowsPrinted++;
            if ($rowsPrinted >= $maxRows) {
                break;
            }
        }

        print '</tbody></table>';
        $tableHtml = (string) ob_get_clean();

        fclose($handle);

        // Cache the rendered HTML so we don't have to re-download and re-process
        // the data on every request.
        $bytesWritten = file_put_contents($cacheFile, $tableHtml, LOCK_EX);
        if ($bytesWritten === false) {
            $error = 'Fetched remote data, but failed to write cache file.';
        }

        $cacheAgeSeconds = is_file($cacheFile) ? (time() - (int) filemtime($cacheFile)) : null;
        $cacheFresh = $cacheAgeSeconds !== null && $cacheAgeSeconds <= $ttlSeconds;
    }
}

require_once __DIR__ . '/../partials/header.php';
?>

