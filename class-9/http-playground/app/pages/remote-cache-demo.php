<dl>
    <dt>Cache exists</dt>
    <dd><?php print is_file($cacheFile) ? 'yes' : 'no'; ?></dd>

    <dt>Cache age (seconds)</dt>
    <dd><?php print $cacheAgeSeconds === null ? '(n/a)' : (int) $cacheAgeSeconds; ?></dd>

    <dt>Cache fresh</dt>
    <dd><?php print $cacheFresh ? 'yes' : 'no'; ?></dd>

    <dt>Source used</dt>
    <dd><?php print h($source); ?></dd>
</dl>

